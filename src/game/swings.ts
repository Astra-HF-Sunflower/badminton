export type SwingKey = keyof typeof SWINGS;

export const readyPose = (): ArmPose => ({
  sh: READY[1], el: READY[2], wr: READY[3], os: READY[4], oe: READY[5], lean: READY[6], crouch: READY[7],
});

export function sampleSwing(id: SwingKey, u: number): ArmPose {
  const keys = SWINGS[id];
  const uu = Math.max(0, Math.min(1, u));
  let i = 0;
  while (i < keys.length - 2 && uu > keys[i + 1][0]) i++;
  const a = keys[i];
  const b = keys[i + 1];
  const t = smooth((uu - a[0]) / (b[0] - a[0]));
  const l = (k: number) => a[k] + (b[k] - a[k]) * t;
  return { sh: l(1), el: l(2), wr: l(3), os: l(4), oe: l(5), lean: l(6), crouch: l(7) };
}
